ts_void fontl_clr_buf_vot(ts_nodebuf_s_t *pst_hosd, ts_u32 u32_bit_width, ts_u32 u32_bg_color, ts_u08 *pu08_fill)
{
	ts_u32 i;
	ts_u08 u08_fill, u08_tmp;

	u08_fill = 0;
	if (TS_PIXEL_BW_1BIT == u32_bit_width) {
		if (u32_bg_color > 0)
			u08_fill = 0xff;
	} else {
		if (u32_bg_color > 0) {
			u08_tmp = u32_bg_color & 0x03;
			for (i = 0; i < 4; i++) {
				u08_fill = u08_fill << 2;
				u08_fill |= u08_tmp;
			}
		}
	}

	if (pu08_fill != ts_null)
		*pu08_fill = u08_fill;

	ts_cpl_memset((ts_void *)pst_hosd->u32_virt_addr, u08_fill, pst_hosd->u32_size);
}


