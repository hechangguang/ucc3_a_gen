static ts_void fontl_clr_buf_1(ts_nodebuf_s_t *pst_hosd, ts_u32 u32_bit_width, ts_fontl_lbl_atts_s_t *pst_attr)
{
    ts_u32 i;
    ts_u08 u08_fill, u08_tmp;
    ts_u08 u32_bg_color;
    ts_u08 *pu08_buf;
    ts_osd_attr_s_t st_osd_attr;

    ts_tdk_osd_get_attr(shdl_osd_dev,pst_hosd, (ts_osd_attr_s_t *)&st_osd_attr);

	u32_bg_color = pst_attr->u08_bg_color;
    u08_fill = 0;
    if (TS_PIXEL_BW_1BIT == u32_bit_width) {
        if (u32_bg_color > 0)
            u08_fill = 0xff;
    } else {
        if (u32_bg_color > 0) {
            u08_tmp = u32_bg_color & 0x03;
            for (i = 0; i < 4; i++) {
                u08_fill = u08_fill << 2;
                u08_fill |= u08_tmp;
            }
        }
    }

	pu08_buf = (ts_u08 *)pst_hosd->u32_virt_addr;
	pu08_buf += (pst_attr->u16_top)*((st_osd_attr.u16_width>>3)<<1) + (pst_attr->u16_left>>2);
	for(i=0; i<pst_attr->u16_height; i++)
	{
		ts_cpl_memset(pu08_buf, u08_fill, (pst_attr->u16_width)>>2);
		pu08_buf += (st_osd_attr.u16_width>>3)<<1;
	}
    //ts_cpl_memset((ts_void *)pst_hosd->u32_virt_addr, u08_fill, pst_hosd->u32_size);
}


