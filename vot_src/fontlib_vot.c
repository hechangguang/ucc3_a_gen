static ts_u32 fontl_get_str_size(const ts_char *pc_str, fontl_strs_s_t *pst_strs)
{
    str_info_s_t *pst_line;
    ts_u32 u32_code, u32_tmp;
    ts_u08 u08_code;
    ts_u32 i, k, width, u32_max_width;

    pst_strs->u32_lines = 0;
    for (i = 0; i < VOT_STR_MAX_LINES; i++) {
        pst_strs->ast_strs[i].u32_num = 0;

        /* 所有字符清成空格 */
        for (k = 0; k < VOT_STR_MAX_NUM; k++)
            pst_strs->ast_strs[i].au32_fonts[k] = ' ';
    }

    i = 0;
    k = 0;
    width = 0;
    u32_max_width = 0;
    pst_line = (str_info_s_t *)&pst_strs->ast_strs[0];
    while (1) {
        /* 换行，如果多个重复换行，则会显示相应空白行 */
        if (('\0' == pc_str[i]) || ('\n' == pc_str[i])) {
            /* 暂时不关心个数，最后需要宽度对齐，会将最大宽度赋值到此 */
            pst_line->u32_num = k;
            pst_line->u32_width = width;
            if (width > u32_max_width)
                u32_max_width = width;

            pst_strs->u32_lines++;
            if ('\0' == pc_str[i]) {
                break;
            } else {
                k = 0;
                width = 0;
                pst_line++;
                
                i++;
                continue;
            }
        }

        u08_code = pc_str[i];
        if (u08_code >= 0x80) {
            /* is utf8 */
            u32_code = u08_code << 16;
            u32_code |= pc_str[i + 1] << 8;
            u32_code |= pc_str[i + 2];
            pst_line->au32_fonts[k] = u32_code;
            i += 3;
            //width += FONT_FULL_WIDTH;
            if (get_powerup_dector_resolution_type()==DECTOR_RESOLUTION_1280X1024)
            {
               width += 4;     
            }
            else
             {
                width += 2;
            }
        } else {
            /* is ascii */
            pst_line->au32_fonts[k] = (ts_u32)u08_code;
            i++;
           // width += FONT_HALF_WIDTH;
            if (get_powerup_dector_resolution_type()==DECTOR_RESOLUTION_1280X1024)
            {
               width += 2;     
            }
            else
             {
                width += 1;
            }
        }

        k++;
        if (k > VOT_STR_MAX_NUM)
            return 0;
    }

    /* 修正每个字段的最大宽度 */
    pst_strs->u32_max_width = u32_max_width;
    for (i = 0; i < pst_strs->u32_lines; i++) {
        if (pst_strs->ast_strs[i].u32_width < pst_strs->u32_max_width) {
            u32_tmp = pst_strs->u32_max_width - pst_strs->ast_strs[i].u32_width;
            u32_tmp = u32_tmp >> 1;

            /* FIXME ： 此处有溢出风险 */
            pst_strs->ast_strs[i].u32_num += u32_tmp;
            pst_strs->ast_strs[i].u32_width = pst_strs->u32_max_width;
        }
    }

    return u32_max_width;
}


