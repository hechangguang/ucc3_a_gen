    if (0 == u32_width)
        return -1;

    /* 一个Item 144像素，最大 17 个 8x8, 1 个 字符width = 8 个像素 */
    u32_tmp = (pst_attr->u16_width - 8);
    if (u32_tmp < (u32_width << 3)) { 
        vision_log_debug("string out of range, %d < %d\n", u32_tmp, (u32_width << 3));

        return -2;
    }

    fontl_lbl_clr_1(pst_lbl, pst_attr);
    // fontl_lbl_clr_font8x8(pst_lbl, pst_attr);

